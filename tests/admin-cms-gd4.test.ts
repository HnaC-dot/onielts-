describe("GĐ4 DB Row Mappers & SEO JSON-LD", () => {
  it("round-trips ConversationTopic including Daily Life part & custom systemPrompt cleanly", () => {
    const sample = {
      ...DEFAULT_CONVERSATION_TOPICS[0],
      part: "Daily Life" as const,
      systemPrompt: "Focus on IELTS Band 8 collocations.",
    };
    expect(uiPartToDbPart("Daily Life")).toBe("part_1");
    expect(uiPartToDbPart("Part 3")).toBe("part_3");
    const dbRow: Record<string, unknown> = {
      id: "uuid-conv-1",
      ...conversationTopicToDbRow(sample, 1),
    };
    expect(dbRow.part).toBe("part_1");
    const mapped = mapConversationRow(dbRow);
    expect(mapped.part).toBe("Daily Life");
    expect(mapped.systemPrompt).toBe("Focus on IELTS Band 8 collocations.");
    expect(mapped.opener).toBe(sample.opener);
    expect(dbPartToUiPart("part_2")).toBe("Part 2");
  });

  it("round-trips WritingExercise preserving practice sentences & criteria", () => {
    const sample = DEFAULT_WRITING_EXERCISES[0];
    const dbRow = { id: "uuid-we-1", ...writingExerciseToDbRow(sample, 1) };
    const mapped = mapWritingExerciseRow(dbRow);
    expect(mapped.slug).toBe(sample.slug);
    expect(mapped.topic).toBe(sample.topic);
    expect(mapped.sentences).toHaveLength(sample.sentences.length);
    expect(mapped.sentences[0].band8Model).toBe(sample.sentences[0].band8Model);
  });

  it("maps PronunciationSound with mouth_image_url and audio_url", () => {
    const mapped = mapPronunciationRow({
      id: "ipa-uuid-1",
      slug: "th-voiceless",
      symbol: "/θ/",
      category: "consonant",
      title_vi: "Phụ âm /θ/",
      title_en: "Voiceless /θ/",
      tip_vi: "Không đọc thành thờ",
      tip_en: "Place tongue gently between teeth",
      examples: {
        mouthPosition_vi: "Đặt lưỡi giữa hai răng",
        practiceSentence: "Think carefully.",
        words: [{ word: "think", ipa: "/θɪŋk/", meaning_vi: "suy nghĩ" }],
      },
      mouth_image_url: "https://cdn.example.com/mouth.png",
      audio_url: "https://cdn.example.com/th.mp3",
      is_published: true,
      sort_order: 5,
    });
    expect(mapped.mouth_image_url).toBe("https://cdn.example.com/mouth.png");
    expect(mapped.audio_url).toBe("https://cdn.example.com/th.mp3");
    expect(mapped.mouthPosition_vi).toBe("Đặt lưỡi giữa hai răng");
    expect(mapped.examples).toHaveLength(1);
  });

  it("generates valid Course and VideoObject JSON-LD schemas", () => {
    const courseLd = buildCourseJsonLd(DEFAULT_COURSES[0], "https://onielts.vn");
    expect(courseLd["@type"]).toBe("Course");
    expect(courseLd.url).toBe(`https://onielts.vn/courses/${DEFAULT_COURSES[0].slug}`);
    expect(courseLd.numberOfLessons).toBe(DEFAULT_COURSES[0].lessons.length);

    const videoLd = buildVideoObjectJsonLd(DEFAULT_LEARN_VIDEOS[0], "https://onielts.vn");
    expect(videoLd["@type"]).toBe("VideoObject");
    expect(videoLd.duration).toBe("PT8M45S");
    expect(videoLd.embedUrl).toContain(DEFAULT_LEARN_VIDEOS[0].youtube_id);
  });
});

